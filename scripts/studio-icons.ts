/**
 * Generate `apps/studio/src/atoms/icons.generated.ts` from the Gravity UI
 * Iconify JSON: one `{ body, width, height }` per key of `ICONS`.
 *
 * Studio then renders inline SVG and ships nothing it does not use — no icon
 * runtime, no fetch, which is what offline-first means for a 438 KB icon set.
 *
 *   npm run studio:icons
 */

import { readFileSync, writeFileSync } from 'node:fs'
import { fileURLToPath, URL } from 'node:url'
import { ICONS } from '../apps/studio/src/atoms/icons'

interface IconifyJSON {
  width?: number
  height?: number
  icons: Record<string, { body: string; width?: number; height?: number }>
}

const source = fileURLToPath(new URL('../node_modules/@iconify-json/gravity-ui/icons.json', import.meta.url))
const target = fileURLToPath(new URL('../apps/studio/src/atoms/icons.generated.ts', import.meta.url))

const set = JSON.parse(readFileSync(source, 'utf8')) as IconifyJSON
const missing: string[] = []

const entries = Object.entries(ICONS).map(([key, name]) => {
  const icon = set.icons[name]
  if (!icon) {
    missing.push(`${key} → ${name}`)
    return ''
  }
  const width = icon.width ?? set.width ?? 16
  const height = icon.height ?? set.height ?? 16
  return `  ${key}: { body: ${JSON.stringify(icon.body)}, width: ${width}, height: ${height} },`
})

if (missing.length > 0) {
  console.error(`icons not in gravity-ui:\n  ${missing.join('\n  ')}`)
  process.exit(1)
}

writeFileSync(
  target,
  `// GENERATED by scripts/studio-icons.ts from @iconify-json/gravity-ui. Do not edit.
// Regenerate with: npm run studio:icons

import type { IconName } from './icons'

export interface IconBody {
  readonly body: string
  readonly width: number
  readonly height: number
}

export const ICON_BODIES: Readonly<Record<IconName, IconBody>> = {
${entries.join('\n')}
}
`,
)

console.log(`wrote ${entries.length} icons to ${target}`)
